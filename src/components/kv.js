import { h } from "../core/dom.js";

/* ============================================================
   STATIC PAGES
   ============================================================ */
export function mi(k, v, dim) {
  return h(
    "div",
    { class: "mi" },
    h("div", { class: "k" }, k),
    h("div", { class: "v" + (dim ? " dim" : "") }, v),
  );
}

